import { Writable } from 'node:stream';
import { pino } from 'pino';
import request from 'supertest';
import { randomUUID } from 'node:crypto';
import { afterEach, describe, it, expect, vi } from 'vitest';
import { createApp } from '../src/app.js';
import {
  ProfileStore,
  profileEnvelope,
} from '../src/modules/employee-profile/webhook.js';
import {
  config,
  profileEvent,
  secret,
  token,
  signature,
  userId,
  webhookPath,
} from './http-fixtures.js';
afterEach(() => vi.useRealTimers());
const send = (
  app: ReturnType<typeof createApp>,
  event: ReturnType<typeof profileEvent>,
  body = JSON.stringify(event),
) =>
  request(app)
    .post(webhookPath)
    .set('Content-Type', 'application/json')
    .set(signature(body, event.messageId))
    .send(body);
describe('Signed profile webhook and volatile state', () => {
  it('matches a golden signature generated by the real backend signer (fictional key)', async () => {
    vi.useFakeTimers({ toFake: ['Date'] });
    vi.setSystemTime(1794009600000);
    await request(createApp(config))
      .post(webhookPath)
      .set('Content-Type', 'application/json')
      .set({
        'webhook-id': '11111111-1111-4111-8111-111111111111',
        'webhook-timestamp': '1794009600',
        'webhook-signature': 'v1,9X6xiWjgl4t132149CWfVQ4gx4rs8B9d4qKzmuq01+U=',
      })
      .send('{"demo":"body"}')
      .expect(400); // Authentication succeeded; contract rejected.
  });
  it('applies only once, preserves bigint revisions, ignores old events and conflicts on identity/revision reuse', async () => {
    const store = new ProfileStore(),
      app = createApp(config, undefined, undefined, store),
      first = profileEvent();
    expect((await send(app, first).expect(200)).body.status).toBe('applied');
    expect((await send(app, first).expect(200)).body.status).toBe('duplicate');
    const old = profileEvent('9007199254740992');
    old.data.employees[0]!.active = false;
    expect((await send(app, old).expect(200)).body.status).toBe('stale');
    const same = profileEvent();
    expect((await send(app, same).expect(200)).body.status).toBe('duplicate');
    same.messageId = randomUUID();
    same.data.employees[0]!.name = 'Conflicting';
    await send(app, same).expect(409);
    first.data.employees[0]!.active = false;
    await send(app, first).expect(409);
    expect(store.snapshot(userId)?.employee.active).toBe(true);
    const next = profileEvent('9007199254740994');
    next.data.employees[0]!.active = false;
    await send(app, next).expect(200);
    expect(store.snapshot(userId)?.revision).toBe(9007199254740994n);
  });
  it('is atomic on capacity rejection and does not evict known duplicates', () => {
    const store = new ProfileStore(1, 2),
      a = profileEvent();
    store.apply(a, Buffer.from(JSON.stringify(a)));
    const b = profileEvent('9007199254740994');
    b.data.employees[0]!._id = randomUUID();
    expect(() => store.apply(b, Buffer.from(JSON.stringify(b)))).toThrow(
      'capacity',
    );
    expect(store.snapshot(b.data.employees[0]!._id)).toBeUndefined();
    b.data.employees[0]!._id = userId;
    store.apply(b, Buffer.from(JSON.stringify(b)));
    const c = profileEvent('9007199254740995');
    expect(() => store.apply(c, Buffer.from(JSON.stringify(c)))).toThrow(
      'capacity',
    );
    expect(store.snapshot(userId)?.revision).toBe(9007199254740994n);
    expect(store.apply(a, Buffer.from(JSON.stringify(a)))).toBe('duplicate');
  });
  it('isolates app instances and serializes concurrent duplicates', async () => {
    const a = createApp(config),
      b = createApp(config),
      event = profileEvent();
    const results = await Promise.all([send(a, event), send(a, event)]);
    expect(results.map((v) => v.body.status).sort()).toEqual([
      'applied',
      'duplicate',
    ]);
    expect((await send(b, event)).body.status).toBe('applied');
  });
  it.each([
    'missing',
    'wrong',
    'expired',
    'future',
    'duplicate',
    'timestamp',
    'tampered',
  ])('rejects %s authentication before parsing', async (kind) => {
    const body = '{broken',
      id = randomUUID(),
      headers: Record<string, string | string[]> = { ...signature(body, id) };
    if (kind === 'missing') delete headers['webhook-signature'];
    if (kind === 'wrong')
      headers['webhook-signature'] =
        'v1,' + Buffer.alloc(32).toString('base64');
    if (kind === 'expired' || kind === 'future')
      Object.assign(
        headers,
        signature(
          body,
          id,
          String(
            Math.floor(Date.now() / 1000) + (kind === 'expired' ? -301 : 301),
          ),
        ),
      );
    if (kind === 'duplicate') headers['webhook-id'] = [id, id];
    if (kind === 'timestamp') headers['webhook-timestamp'] = 'not-a-timestamp';
    if (kind === 'tampered') Object.assign(headers, signature('different', id));
    await request(createApp(config))
      .post(webhookPath)
      .set('Content-Type', 'application/json')
      .set(headers)
      .send(body)
      .expect(401);
  });
  it('rejects malformed signed JSON, mismatched IDs and over-limit raw bodies', async () => {
    const app = createApp(config),
      event = profileEvent();
    await send(app, event, '{broken').expect(400);
    const body = JSON.stringify(event);
    await request(app)
      .post(webhookPath)
      .set('Content-Type', 'application/json')
      .set(signature(body, randomUUID()))
      .send(body)
      .expect(400);
    await send(app, event, 'x'.repeat(256 * 1024 + 1)).expect(413);
  });
  it('accepts an exactly256 KiB signed body and rejects an unconfigured receiver', async () => {
    const e = profileEvent(),
      json = JSON.stringify(e),
      body = json + ' '.repeat(256 * 1024 - Buffer.byteLength(json));
    await send(createApp(config), e, body).expect(200);
    await send(createApp({ ...config, rita: {} }), e).expect(503);
  });
  it.each([
    {},
    { type: 'employee.profiles.changed' },
    { source: 'other' },
    { schemaVersion: 2 },
    { revision: '9007199254740993.1' },
    { revision: '0' },
    { revision: '9223372036854775808' },
    { occurredAt: '2026-02-30T00:00:00Z' },
    { data: { syncRunId: randomUUID(), employees: [] } },
  ])('validates exact envelope %j', (patch) => {
    if (Object.keys(patch).length === 0) {
      expect(() => profileEnvelope.parse({})).toThrow();
      return;
    }
    expect(() =>
      profileEnvelope.parse({ ...profileEvent(), ...patch }),
    ).toThrow();
  });
  it('rejects batch/extra/invalid employee fields and preserves nullable projection', () => {
    const e = profileEvent();
    expect(profileEnvelope.parse(e).data.employees[0]!.employee_id).toBeNull();
    e.data.employees.push(e.data.employees[0]!);
    expect(() => profileEnvelope.parse(e)).toThrow();
    for (const patch of [
      { groups: 'CUSTOMER' },
      { employee_id: 1 },
      { active: 'false' },
      { position: { text: null, parser: {} } },
      { extra: true },
    ])
      expect(() =>
        profileEnvelope.parse({
          ...profileEvent(),
          data: {
            ...e.data,
            employees: [{ ...profileEvent().data.employees[0], ...patch }],
          },
        }),
      ).toThrow();
  });

  it('logs the entire validated envelope without transport credentials or raw request fields', async () => {
    const log = vi.fn(),
      app = createApp(config, { info: log, error: log } as never),
      event = profileEvent();
    const body = JSON.stringify(event),
      headers = signature(body, event.messageId);
    await request(app)
      .post(webhookPath)
      .set('Content-Type', 'application/json')
      .set(headers)
      .set('Authorization', 'Bearer ' + token)
      .set('X-API-Key', config.rita.apiKey!)
      .send(body)
      .expect(200);
    const received = log.mock.calls.filter(
      ([, message]) => message === 'Profile webhook received',
    );
    expect(received).toHaveLength(1);
    expect(received[0]![0]).toEqual({
      event: 'profile_webhook_received',
      messageId: event.messageId,
      revision: event.revision,
      payload: event,
    });
    const output = JSON.stringify(log.mock.calls);
    expect(output).toContain('fictional@example.test');
    for (const forbidden of [
      secret,
      token,
      config.rita.apiKey!,
      headers['webhook-signature'],
      'Authorization',
      'webhook-signature',
      'webhook-timestamp',
      'rawBody',
    ])
      expect(output).not.toContain(forbidden);
    const processed = log.mock.calls.find(
      ([, message]) => message === 'Profile webhook processed in RAM',
    );
    expect(processed?.[0]).toMatchObject({
      messageId: event.messageId,
      revision: event.revision,
      outcome: 'applied',
      durationMs: expect.any(Number),
    });
    expect(processed?.[0]).not.toHaveProperty('payload');
    expect(
      log.mock.calls.find(([, message]) => message === 'HTTP request')?.[0],
    ).toMatchObject({ method: 'POST', path: webhookPath, status: 200 });
  });
  it.each(['applied', 'duplicate', 'stale', 'conflict', 'capacity'] as const)(
    'logs one received payload before RAM processing for %s',
    async (kind) => {
      const log = vi.fn(),
        store = new ProfileStore(kind === 'capacity' ? 0 : 1000),
        app = createApp(
          config,
          { info: log, error: log } as never,
          undefined,
          store,
        ),
        event = profileEvent();
      if (kind === 'duplicate' || kind === 'conflict')
        await send(app, event).expect(200);
      if (kind === 'stale')
        await send(app, profileEvent('9007199254740994')).expect(200);
      if (kind === 'conflict')
        event.data.employees[0]!.name = 'Conflicting fictional profile';
      log.mockClear();
      const apply = vi.spyOn(store, 'apply');
      const expectedStatus =
        kind === 'conflict' ? 409 : kind === 'capacity' ? 503 : 200;
      const response = await send(app, event).expect(expectedStatus);
      const receivedIndexes = log.mock.calls.flatMap(([, message], index) =>
        message === 'Profile webhook received' ? [index] : [],
      );
      expect(receivedIndexes).toHaveLength(1);
      const receivedIndex = receivedIndexes[0]!;
      expect(log.mock.calls[receivedIndex]![0]).toMatchObject({
        event: 'profile_webhook_received',
        messageId: event.messageId,
        revision: event.revision,
        payload: event,
      });
      expect(log.mock.invocationCallOrder[receivedIndex]).toBeLessThan(
        apply.mock.invocationCallOrder[0]!,
      );
      const processed = log.mock.calls.filter(
        ([, message]) => message === 'Profile webhook processed in RAM',
      );
      if (expectedStatus === 200) {
        expect(response.body).toEqual({
          messageId: event.messageId,
          status: kind,
        });
        expect(processed).toHaveLength(1);
        expect(processed[0]![0]).toMatchObject({ outcome: kind });
      } else {
        expect(processed).toHaveLength(0);
        expect(response.body.error.code).toBe(
          kind === 'conflict'
            ? 'EVENT_IDENTITY_CONFLICT'
            : 'DEMO_CAPACITY_REACHED',
        );
      }
      apply.mockRestore();
    },
  );
  it.each([
    'signature',
    'expired',
    'missing-header',
    'duplicate-header',
    'malformed-json',
    'schema',
    'id-mismatch',
    'unconfigured',
    'oversized',
  ] as const)(
    'does not log payload rejected before processing: %s',
    async (kind) => {
      const log = vi.fn(),
        event = profileEvent();
      let body = JSON.stringify(event);
      if (kind === 'malformed-json') body = '{broken';
      if (kind === 'schema')
        body = JSON.stringify({ ...event, schemaVersion: 2 });
      if (kind === 'oversized') body = 'x'.repeat(256 * 1024 + 1);
      const headers: Record<string, string | string[]> = {
        ...signature(body, event.messageId),
      };
      if (kind === 'signature')
        headers['webhook-signature'] =
          'v1,' + Buffer.alloc(32).toString('base64');
      if (kind === 'expired')
        Object.assign(
          headers,
          signature(
            body,
            event.messageId,
            String(Math.floor(Date.now() / 1000) - 301),
          ),
        );
      if (kind === 'missing-header') delete headers['webhook-signature'];
      if (kind === 'duplicate-header')
        headers['webhook-id'] = [event.messageId, event.messageId];
      if (kind === 'id-mismatch')
        Object.assign(headers, signature(body, randomUUID()));
      const app = createApp(
        kind === 'unconfigured'
          ? { ...config, rita: { ...config.rita, webhookSecret: undefined } }
          : config,
        { info: log, error: log } as never,
      );
      const expected =
        kind === 'oversized'
          ? 413
          : kind === 'unconfigured'
            ? 503
            : ['malformed-json', 'schema', 'id-mismatch'].includes(kind)
              ? 400
              : 401;
      await request(app)
        .post(webhookPath)
        .set('Content-Type', 'application/json')
        .set(headers)
        .send(body)
        .expect(expected);
      expect(
        log.mock.calls.filter(
          ([, message]) => message === 'Profile webhook received',
        ),
      ).toHaveLength(0);
      expect(
        log.mock.calls.filter(
          ([, message]) => message === 'Profile webhook processed in RAM',
        ),
      ).toHaveLength(0);
      for (const [record] of log.mock.calls)
        expect(record).not.toHaveProperty('payload');
      expect(JSON.stringify(log.mock.calls)).not.toContain(
        'fictional@example.test',
      );
    },
  );
  it.each(['info', 'warn'] as const)(
    'honors Pino level %s without a separate payload flag',
    async (level) => {
      let output = '';
      const stream = new Writable({
        write(chunk, _encoding, callback) {
          output += String(chunk);
          callback();
        },
      });
      const logger = pino(
          { level, base: { service: 'fictional-example' } },
          stream,
        ),
        event = profileEvent();
      await send(createApp(config, logger), event).expect(200);
      const records: Record<string, unknown>[] = output.trim()
        ? output
            .trim()
            .split('\n')
            .map((line) => JSON.parse(line) as Record<string, unknown>)
        : [];
      const received = records.filter(
        (record) => record.event === 'profile_webhook_received',
      );
      expect(received).toHaveLength(level === 'info' ? 1 : 0);
      if (level === 'info')
        expect(received[0]).toMatchObject({
          payload: event,
          msg: 'Profile webhook received',
        });
    },
  );
});
